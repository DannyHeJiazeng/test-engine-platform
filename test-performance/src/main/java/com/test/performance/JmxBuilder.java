package com.test.performance;

import lombok.extern.slf4j.Slf4j;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Map;

/**
 * JMX 文件构建器
 * 用于生成 JMeter JMX 测试计划文件
 */
@Slf4j
public class JmxBuilder {

    private static final DateTimeFormatter DATE_FORMATTER = DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss");

    public JmxBuilder() {
        // 默认构造函数
    }

    /**
     * 构建 JMX 文件
     */
    public String buildJmx(PerformanceConfig config) {
        String jmxContent = generateJmxContent(config);
        String jmxFilePath = saveJmxFile(jmxContent, config.getTestName());
        log.info("JMX file created: {}", jmxFilePath);
        return jmxFilePath;
    }

    /**
     * 生成 JMX 内容
     */
    private String generateJmxContent(PerformanceConfig config) {
        StringBuilder jmx = new StringBuilder();

        jmx.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
           .append("<jmeterTestPlan>\n")
           .append("  <hashTree>\n")
           .append("    <TestPlan guiclass=\"TestPlanGui\" testclass=\"TestPlan\" testname=\"")
           .append(escapeXml(config.getTestName()))
           .append("\" enabled=\"true\">\n")
           .append("      <stringProp name=\"TestPlan.comments\">Generated by Test Engine Platform</stringProp>\n")
           .append("      <boolProp name=\"TestPlan.functional_mode\">false</boolProp>\n")
           .append("      <boolProp name=\"TestPlan.tearDown_on_shutdown\">true</boolProp>\n")
           .append("      <boolProp name=\"TestPlan.serialize_threadgroups\">false</boolProp>\n")
           .append("    </TestPlan>\n")
           .append("    <hashTree>\n");

        // Thread Group
        jmx.append(buildThreadGroup(config));

        // HTTP Request
        jmx.append(buildHttpRequest(config));

        // Response Assertion
        jmx.append(buildResponseAssertion(config));

        jmx.append("    </hashTree>\n")
           .append("  </hashTree>\n")
           .append("</jmeterTestPlan>\n");

        return jmx.toString();
    }

    private String buildThreadGroup(PerformanceConfig config) {
        return "      <ThreadGroup guiclass=\"ThreadGroupGui\" testclass=\"ThreadGroup\" testname=\"Thread Group\" enabled=\"true\">\n" +
               "        <stringProp name=\"ThreadGroup.num_threads\">" + config.getThreads() + "</stringProp>\n" +
               "        <stringProp name=\"ThreadGroup.ramp_time\">" + config.getRampUpSeconds() + "</stringProp>\n" +
               "        <boolProp name=\"ThreadGroup.scheduler\">true</boolProp>\n" +
               "        <stringProp name=\"ThreadGroup.duration\">" + (config.getDurationSeconds() * 1000) + "</stringProp>\n" +
               "      </ThreadGroup>\n" +
               "      <hashTree>\n";
    }

    private String buildHttpRequest(PerformanceConfig config) {
        String method = config.getMethod();
        String url = config.getUrl();

        String protocol = "http";
        String host = url;
        int port = 80;
        String path = "/";

        try {
            java.net.URL parsedUrl = new java.net.URL(url);
            protocol = parsedUrl.getProtocol();
            host = parsedUrl.getHost();
            port = parsedUrl.getPort();
            if (port == -1) {
                port = "https".equals(protocol) ? 443 : 80;
            }
            path = parsedUrl.getPath();
            if (path.isEmpty()) {
                path = "/";
            }
        } catch (Exception e) {
            log.warn("Failed to parse URL, using as-is: {}", url);
        }

        return "        <HTTPSamplerProxy guiclass=\"HttpTestSampleGui\" testclass=\"HTTPSamplerProxy\" testname=\"HTTP Request\" enabled=\"true\">\n" +
               "          <stringProp name=\"HTTPSampler.domain\">" + host + "</stringProp>\n" +
               "          <stringProp name=\"HTTPSampler.port\">" + port + "</stringProp>\n" +
               "          <stringProp name=\"HTTPSampler.protocol\">" + protocol + "</stringProp>\n" +
               "          <stringProp name=\"HTTPSampler.path\">" + path + "</stringProp>\n" +
               "          <stringProp name=\"HTTPSampler.method\">" + method + "</stringProp>\n" +
               "        </HTTPSamplerProxy>\n" +
               "        <hashTree/>\n";
    }

    private String buildResponseAssertion(PerformanceConfig config) {
        return "      <ResponseAssertion guiclass=\"AssertionGui\" testclass=\"ResponseAssertion\" testname=\"Response Assertion\" enabled=\"true\">\n" +
               "        <stringProp name=\"Assertion.test_field\">Assertion.response_code</stringProp>\n" +
               "        <intProp name=\"Assertion.test_type\">2</intProp>\n" +
               "      </ResponseAssertion>\n" +
               "      <hashTree/>\n";
    }

    private String saveJmxFile(String content, String testName) {
        try {
            String timestamp = LocalDateTime.now().format(DATE_FORMATTER);
            String fileName = testName.replaceAll("[^a-zA-Z0-9]", "_") + "_" + timestamp + ".jmx";
            Path outputDir = Paths.get("jmx-files");
            Files.createDirectories(outputDir);
            Path jmxFile = outputDir.resolve(fileName);

            try (FileWriter writer = new FileWriter(jmxFile.toFile())) {
                writer.write(content);
            }

            return jmxFile.toString();

        } catch (IOException e) {
            log.error("Failed to save JMX file", e);
            throw new RuntimeException("Failed to save JMX file", e);
        }
    }

    private String escapeXml(String input) {
        if (input == null) return "";
        return input.replace("&", "&amp;")
                    .replace("<", "&lt;")
                    .replace(">", "&gt;")
                    .replace("\"", "&quot;")
                    .replace("'", "&apos;");
    }
}
